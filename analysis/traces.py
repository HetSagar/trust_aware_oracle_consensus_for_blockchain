"""Example decision traces where mechanisms disagree (Plan Phase 5).

    python analysis/traces.py analysis/out/traces.md
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from landval.model import CHECKS, MECHANISMS, ORACLES, Params, TrustStore, validate  # noqa: E402
from landval.world import SCENARIOS, make_world  # noqa: E402

SYM = {1: "+", -1: "−", None: "∅"}


def trace(sc_name, seed, want):
    """First transfer where `want(decisions, world, t)` holds; replays trust under F0."""
    sc = SCENARIOS[sc_name]
    w = make_world(sc, seed)
    A, p = sc.authority_dict(), Params()
    stores = {m: TrustStore(p.t0) for m in MECHANISMS}
    for t in range(sc.n):
        dec = {m: validate(w.reports[t], stores[m], A, MECHANISMS[m], p) for m in MECHANISMS}
        if want(dec, w, t):
            return w, t, dec, stores
        for m, mech in MECHANISMS.items():
            if mech.learns:
                stores[m].update(w.reports[t], w.truth[t], p.alpha)
    return None


def render(title, sc_name, seed, res):
    w, t, dec, stores = res
    lines = [f"## {title}", "", f"Scenario {sc_name}, seed {seed}, transfer {t + 1}. "
             f"Truth: " + ", ".join(f"{k} {'pass' if w.truth[t][k] == 1 else 'fail'}" for k in CHECKS)
             + f" → {'valid' if w.valid(t) else 'INVALID'}.", "",
             "| Office | own | deed | restr | trust in P (own / deed / restr) |", "| --- | --- | --- | --- | --- |"]
    for i in ORACLES:
        tr = " / ".join(f"{stores['P'].raw(i, k):.2f}" for k in CHECKS)
        lines.append(f"| {i} | " + " | ".join(SYM[w.reports[t][(i, k)]] for k in CHECKS) + f" | {tr} |")
    lines += ["", "| Mechanism | Decision | Reasons |", "| --- | --- | --- |"]
    for m, d in dec.items():
        lines.append(f"| {m} | {d.label} | {', '.join(d.reasons) or '—'} |")
    return "\n".join(lines) + "\n"


def main(out):
    cases = [
        ("Majority commits an invalid transfer that the hybrid escalates", "S1", 1,
         lambda d, w, t: d["B1"].commit and not w.valid(t) and not d["P-V"].commit),
        ("After Revenue degrades, trust lets the hybrid outvote it", "S2", 1,
         lambda d, w, t: t >= 400 and w.valid(t) and d["P-V"].commit and not d["B2"].commit),
        ("A pending proceeding hidden from Revenue and Sub-Registrar", "S5a", 1,
         lambda d, w, t: w.truth[t]["restr"] == -1 and d["B1"].commit and not d["P"].commit),
    ]
    parts = ["# Decision traces\n\nGenerated by analysis/traces.py from the frozen model; "
             "trust is replayed under ideal feedback (F0).\n"]
    for title, sc, seed, f in cases:
        r = trace(sc, seed, f)
        parts.append(render(title, sc, seed, r) if r else f"## {title}\n\nNo case found.\n")
    Path(out).write_text("\n".join(parts))
    print("\n".join(parts))


if __name__ == "__main__":
    main(sys.argv[1])
